"""Infinitesimal diffeomorphisms of the perturbation.

Sign and active/passive discussion
----------------------------------
A diffeomorphism generated by the vector field xi^m changes the full metric by
-eps L_xi g (passive: new coordinates x'^m = x^m + eps xi^m, so the metric
components as functions of the new coordinates are g'(x') = g - eps L_xi g).
Expanding g = gbar + eps h the background is unchanged at O(1) and

    h_{mn} -> h_{mn} - (L_xi gbar)_{mn} = h_{mn} - nabla_m xi_n - nabla_n xi_m ,

with xi_m = gbar_{mn} xi^n and nabla the background connection.  The opposite
(active) convention corresponds to xi -> -xi and nothing physical depends on it;
what matters is that the field equations and every gauge invariant be
consistent with the single choice made here.

For flat-sliced de Sitter in conformal time the scalar-vector-tensor
transformation laws (derived and verified symbolically below) are, for
xi^m = (T, d^i L + L^i):

    A -> A - (calH T + T'),   B -> B + T - L',   psi -> psi + calH T,
    E -> E - L,   S_i -> S_i - L_i',   F_i -> F_i - L_i,   gamma_ij -> gamma_ij,

where the perturbed metric is
    ds^2 = a^2 [ -(1+2A) d eta^2 + 2 (d_i B + S_i) d eta dx^i
                 + ((1-2 psi) delta_ij + 2 d_i d_j E + d_i F_j + d_j F_i + gamma_ij) dx^i dx^j ].
"""

from __future__ import annotations

import functools

import itertools
import sympy as sp

from .connections import cov_deriv_covariant


def lie_derivative_metric(xi_up, g: sp.Matrix, coords):
    """(L_xi g)_{mn} = xi^r d_r g_{mn} + g_{rn} d_m xi^r + g_{mr} d_n xi^r."""
    n = len(coords)
    out = sp.zeros(n, n)
    for m in range(n):
        for nn in range(n):
            v = sum(xi_up[r] * sp.diff(g[m, nn], coords[r]) for r in range(n))
            v += sum(g[r, nn] * sp.diff(xi_up[r], coords[m]) for r in range(n))
            v += sum(g[m, r] * sp.diff(xi_up[r], coords[nn]) for r in range(n))
            out[m, nn] = v
    return out


def covariant_symmetrized_gradient(xi_down, Gam, coords):
    """nabla_m xi_n + nabla_n xi_m (background connection)."""
    n = len(coords)
    xi = {(i,): xi_down[i] for i in range(n)}
    D = cov_deriv_covariant(xi, Gam, coords, 1)
    return sp.Matrix(n, n, lambda m, nn: D[(m, nn)] + D[(nn, m)])


def pure_gauge_perturbation(xi_up, geom_bar, simp=sp.simplify):
    """h_pg = -(nabla_m xi_n + nabla_n xi_m), computed from xi^m via the covariant formula."""
    xi_down = list(geom_bar.g * sp.Matrix(xi_up))
    h = -covariant_symmetrized_gradient(xi_down, geom_bar.Gamma, geom_bar.coords)
    return h.applyfunc(simp)


def lie_equals_covariant_residual(xi_up, geom_bar, simp=sp.simplify):
    """(L_xi gbar) - (nabla xi + nabla xi): must vanish."""
    L = lie_derivative_metric(xi_up, geom_bar.g, geom_bar.coords)
    xi_down = list(geom_bar.g * sp.Matrix(xi_up))
    C = covariant_symmetrized_gradient(xi_down, geom_bar.Gamma, geom_bar.coords)
    return (L - C).applyfunc(simp)


# ---------------------------------------------------------------- SVT laws

@functools.lru_cache(maxsize=None)
def svt_transformation_laws():
    """Derive the SVT transformation laws for flat dS in conformal time.

    A single scalar-vector decomposition is used with all fields depending on
    (eta, z) only (enough to expose every law; vector fields point along x).
    Returns a dict of sympy expressions for the *shift* (new - old) of each field,
    obtained by matching components of  - L_xi gbar  against the SVT ansatz.
    """
    eta = sp.Symbol("eta", negative=True)
    H = sp.Symbol("H", positive=True)
    X, Y, Z = sp.symbols("x y z", real=True)
    coords = (eta, X, Y, Z)
    a = -1 / (H * eta)
    gbar = sp.diag(-a**2, a**2, a**2, a**2)
    T = sp.Function("T")(eta, Z)
    L = sp.Function("L")(eta, Z)
    Lx = sp.Function("Lx")(eta, Z)  # transverse vector gauge parameter along x
    xi_up = [T, Lx, 0, sp.diff(L, Z)]
    Lie = lie_derivative_metric(xi_up, gbar, coords)
    dh = (-Lie).applyfunc(sp.simplify)  # shift of h
    calH = -1 / eta
    # match components:  h_00 = -2 a^2 A ; h_0z = a^2 d_z B ; h_0x = a^2 S_x ;
    # h_zz = a^2(-2 psi + 2 d_z^2 E) ; h_xx = a^2 (-2 psi) ; h_xz = a^2 d_z F_x
    dA = sp.simplify(dh[0, 0] / (-2 * a**2))
    dS_x = sp.simplify(dh[0, 1] / a**2)
    dB_z = sp.simplify(dh[0, 3] / a**2)     # = d_z (shift of B)
    dpsi = sp.simplify(dh[1, 1] / (-2 * a**2))
    dE_zz = sp.simplify(dh[3, 3] / a**2 + 2 * dpsi)  # = 2 d_z^2 (shift of E)
    dF_xz = sp.simplify(dh[1, 3] / a**2)    # = d_z (shift of F_x)
    return {
        "eta": eta, "H": H, "z": Z, "T": T, "L": L, "Lx": Lx, "calH": calH,
        "dh": dh,
        "dA": dA, "dS_x": dS_x, "dB_z": dB_z, "dpsi": dpsi, "dE_zz": dE_zz, "dF_xz": dF_xz,
        "dh_xy": dh[1, 2], "dh_yz": dh[2, 3], "dh_0y": dh[0, 2], "dh_yy": dh[2, 2],
    }


def check_svt_laws():
    """Return residuals against the closed-form laws quoted in the module docstring."""
    s = svt_transformation_laws()
    eta, Z, T, L, Lx, cH = s["eta"], s["z"], s["T"], s["L"], s["Lx"], s["calH"]
    res = {
        "A": sp.simplify(s["dA"] - (-(cH * T + sp.diff(T, eta)))),
        "psi": sp.simplify(s["dpsi"] - cH * T),
        "S_x": sp.simplify(s["dS_x"] - (-sp.diff(Lx, eta))),
        "B_z": sp.simplify(s["dB_z"] - sp.diff(T - sp.diff(L, eta), Z)),
        "E_zz": sp.simplify(s["dE_zz"] - 2 * sp.diff(-L, Z, 2)),
        "F_xz": sp.simplify(s["dF_xz"] - sp.diff(-Lx, Z)),
    }
    return res
