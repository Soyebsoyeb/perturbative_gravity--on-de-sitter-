#!/usr/bin/env python3
"""Generate every figure into figures/<subdir>/ and write reports/figure_catalog.md."""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from desitter_perturbations.visualization import (background_plots as bp, geometry_plots as gp, gauge_plots as gaup,  # noqa: E402
                                                  mode_plots as mp, spectrum_plots as sp_, convergence_plots as cp,
                                                  phase_space_plots as pp)

CATALOG = [
    ("geometry/background_evolution", "Scale factor, conformal time and comoving Hubble radius of flat de Sitter space.", bp.plot_background_evolution),
    ("geometry/horizon_crossing", "Horizon crossing $k/(aH)=1$ for three wavenumbers, in e-folds and in conformal time.", bp.plot_horizon_crossing),
    ("geometry/expansion_truncation_errors", "Truncation error of the inverse-metric and $\\sqrt{-g}$ expansions: slopes $1,2,3$ confirm correct order.", gp.plot_expansion_errors),
    ("geometry/curvature_sign_check", "Ricci scalar from the symbolic engine; a flipped Riemann sign is detected.", gp.plot_curvature_invariants),
    ("gauge/gauge_comparison", "One scalar perturbation in three gauges: $A$ and $\\psi$ change; Bardeen potentials do not.", gaup.plot_gauge_comparison),
    ("perturbations/svt_diagnostics", "Spectral SVT round trip, transversality of the TT part, small-$k$ error amplification.", gaup.plot_svt_diagnostics),
    ("dynamics/mode_evolution", "Tensor mode amplitude and oscillation versus $x=k/(aH)$: decay inside, freeze-out outside.", mp.plot_mode_evolution),
    ("dynamics/formulation_comparison", "Four formulations of the mode equation agree to the solver tolerance.", mp.plot_formulation_comparison),
    ("dynamics/phase_space_and_wronskian", "Canonical phase space, mode function and Wronskian conservation.", pp.plot_phase_space),
    ("spectra/tensor_spectrum", "Tensor power spectrum at fixed conformal time versus k, numerical vs exact.", sp_.plot_tensor_spectrum),
    ("spectra/late_time_freezeout", "Freeze-out of the tensor spectrum; departure is $x^2$.", sp_.plot_late_time),
    ("spectra/initial_state_dependence", "Excited initial states and finite-start-time error as a Bogoliubov mixing.", sp_.plot_bogoliubov_and_start),
    ("spectra/scaling_H_Mpl", "$\\Delta_t^2$ scales as $H^2/M_{\\rm pl}^2$.", sp_.plot_scaling_H_M),
    ("validation/residual_diagnostics", "ODE residual of the stored solution is set by interpolation error (4th order).", mp.plot_residual_diagnostics),
    ("validation/tolerance_and_horizon_crossing", "Error tracks $\\mathrm{rtol}$ and does not spike at horizon crossing.", cp.plot_tolerance_and_trajectory),
    ("validation/solver_methods_and_order", "Solver comparison and fixed-step RK4 order-of-convergence study.", cp.plot_methods_and_order),
]


def main():
    lines = ["# Figure catalog", "", "All figures are generated by `scripts/generate_all_figures.py`.", ""]
    meta = {}
    for name, caption, fn in CATALOG:
        out = fn()
        path = out[0] if isinstance(out, tuple) else out
        print("wrote", path)
        meta[name] = caption
        lines += [f"## {name}", "", f"![{name}](../figures/{name}.png)", "", caption, ""]
    (ROOT / "reports" / "figure_catalog.md").write_text("\n".join(lines))
    (ROOT / "data" / "generated" / "figure_catalog.json").write_text(json.dumps(meta, indent=2))


if __name__ == "__main__":
    main()
